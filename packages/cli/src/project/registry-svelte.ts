const SVELTEKIT_PLUGIN_CALL = /\bsveltekit\(/
const VITE_CONFIG_CANDIDATES = ['vite.config.ts', 'vite.config.mts', 'vite.config.js', 'vite.config.mjs'] as const
const SVELTE_CONFIG_UNSUPPORTED_MESSAGE = 'svelte.config.js is not supported by SvelteKit 3. Move its options into the sveltekit() plugin in vite.config.ts, then delete svelte.config.js.'
const VITE_CONFIG_WRAP_MESSAGE = 'Could not patch vite.config.ts with withHoloSvelteKit(). Call sveltekit() in vite.config.ts so holo prepare can manage the SvelteKit integration.'

const WRAPPER_IMPORT_PATTERN = /import\s*\{([^}]*)\}\s*from\s*['"]@holo-js\/adapter-sveltekit\/config['"]/g
const REGEX_PRECEDING_KEYWORD = /(^|[^\w$])(return|typeof|case|do|else|in|of|new|delete|void|throw|yield|await)$/

function blankOut(text: string): string {
  return text.replace(/[^\n]/g, ' ')
}

function skipLineComment(source: string, index: number): number {
  const newline = source.indexOf('\n', index)
  return newline === -1 ? source.length : newline
}

function skipBlockComment(source: string, index: number): number {
  const close = source.indexOf('*/', index + 2)
  return close === -1 ? source.length : close + 2
}

function skipQuoted(source: string, index: number): number {
  const quote = source[index]
  let cursor = index + 1
  while (cursor < source.length) {
    const char = source[cursor]
    if (char === '\\') {
      cursor += 2
    } else if (quote === '`' && char === '$' && source[cursor + 1] === '{') {
      cursor = skipCodeBlock(source, cursor + 2)
    } else if (char === quote) {
      return cursor + 1
    } else {
      cursor += 1
    }
  }

  return source.length
}

function skipCodeBlock(source: string, index: number): number {
  let depth = 1
  let cursor = index
  while (cursor < source.length) {
    const char = source[cursor]
    const next = source[cursor + 1]
    if (char === '/' && next === '/') {
      cursor = skipLineComment(source, cursor)
    } else if (char === '/' && next === '*') {
      cursor = skipBlockComment(source, cursor)
    } else if (char === '\'' || char === '"' || char === '`') {
      cursor = skipQuoted(source, cursor)
    } else {
      if (char === '{') {
        depth += 1
      } else if (char === '}') {
        depth -= 1
        if (depth === 0) return cursor + 1
      }
      cursor += 1
    }
  }

  return source.length
}

function skipRegex(source: string, index: number): number {
  let cursor = index + 1
  let inClass = false
  while (cursor < source.length) {
    const char = source[cursor]
    if (char === '\n') return -1
    if (char === '\\') {
      cursor += 2
    } else if (inClass) {
      if (char === ']') inClass = false
      cursor += 1
    } else if (char === '[') {
      inClass = true
      cursor += 1
    } else if (char === '/') {
      cursor += 1
      while (cursor < source.length && /[\w$]/.test(source[cursor] as string)) cursor += 1
      return cursor
    } else {
      cursor += 1
    }
  }

  return -1
}

function regexAllowedAfter(code: string): boolean {
  const trimmed = code.trimEnd()
  if (trimmed === '') return true
  if (/[(,=:[!&|?{};+\-*%<>~^]$/.test(trimmed)) return true
  return REGEX_PRECEDING_KEYWORD.test(trimmed)
}

function maskNonCode(source: string): string {
  let masked = ''
  let index = 0
  while (index < source.length) {
    const char = source[index] as string
    const next = source[index + 1]
    let end = -1
    if (char === '/' && next === '/') {
      end = skipLineComment(source, index)
    } else if (char === '/' && next === '*') {
      end = skipBlockComment(source, index)
    } else if (char === '\'' || char === '"' || char === '`') {
      end = skipQuoted(source, index)
    } else if (char === '/' && regexAllowedAfter(masked)) {
      end = skipRegex(source, index)
    }

    if (end === -1) {
      masked += char
      index += 1
    } else {
      masked += blankOut(source.slice(index, end))
      index = end
    }
  }

  return masked
}

function findClosingParen(code: string, openIndex: number): number {
  let depth = 0
  for (let index = openIndex; index < code.length; index += 1) {
    if (code[index] === '(') {
      depth += 1
    } else if (code[index] === ')') {
      depth -= 1
      if (depth === 0) return index
    }
  }

  return -1
}

function assertNoCustomHookOverride(pluginOptions: string, pluginCode: string): void {
  if (pluginOptions.includes('.holo-js/generated/hooks')) {
    return
  }

  if (/files\s*:\s*\{[\s\S]*?hooks\s*:/.test(pluginCode)) {
    throw new Error('Custom SvelteKit hook entrypoints are not supported. Remove files.hooks from the sveltekit() options and let holo prepare manage the generated hook bridge.')
  }
}

function hasPlainWrapperImport(contents: string): boolean {
  return [...contents.matchAll(WRAPPER_IMPORT_PATTERN)].some(match => (match[1] ?? '').split(',').map(specifier => specifier.trim()).includes('withHoloSvelteKit'))
}

function ensureWrapperImport(contents: string): string {
  if (hasPlainWrapperImport(contents)) {
    return contents
  }

  const firstImport = maskNonCode(contents).search(/^import\s/m)
  if (firstImport === -1) {
    return `${SVELTE_CONFIG_WRAPPER_IMPORT}\n${contents}`
  }

  return `${contents.slice(0, firstImport)}${SVELTE_CONFIG_WRAPPER_IMPORT}\n${contents.slice(firstImport)}`
}

function patchViteConfigWithHoloWrapper(contents: string): string | undefined {
  const code = maskNonCode(contents)
  const call = SVELTEKIT_PLUGIN_CALL.exec(code)
  if (!call) {
    throw new Error(VITE_CONFIG_WRAP_MESSAGE)
  }

  const openIndex = call.index + call[0].length - 1
  const closeIndex = findClosingParen(code, openIndex)
  if (closeIndex === -1) {
    throw new Error(VITE_CONFIG_WRAP_MESSAGE)
  }

  const pluginOptions = contents.slice(openIndex + 1, closeIndex)
  const pluginCode = code.slice(openIndex + 1, closeIndex)
  assertNoCustomHookOverride(pluginOptions, pluginCode)
  const alreadyWrapped = pluginCode.trimStart().startsWith(SVELTE_CONFIG_WRAPPER_CALL)
  const wrapped = alreadyWrapped
    ? contents
    : `${contents.slice(0, openIndex + 1)}${SVELTE_CONFIG_WRAPPER_CALL}${pluginOptions})${contents.slice(closeIndex)}`
  const withImport = ensureWrapperImport(wrapped)
  return withImport === contents ? undefined : withImport
}

async function ensureViteConfigWrapsSvelteKit(projectRoot: string): Promise<void> {
  if (await pathExists(resolve(projectRoot, 'svelte.config.js'))) {
    throw new Error(SVELTE_CONFIG_UNSUPPORTED_MESSAGE)
  }

  for (const name of VITE_CONFIG_CANDIDATES) {
    const configPath = resolve(projectRoot, name)
    const contents = await readFileIfPresent(configPath)
    if (contents === undefined) {
      continue
    }

    const patched = patchViteConfigWithHoloWrapper(contents) ?? contents
    if (patched !== contents) {
      await writeTextFile(configPath, patched)
    }
    return
  }
}

async function writeFileIfChanged(path: string, contents: string): Promise<boolean> {
  const existing = await readFileIfPresent(path)
  if (existing === contents) return false

  await writeTextFile(path, contents)
  return existing === undefined
}

async function ensureSvelteManagedHooks(projectRoot: string, features: SvelteManagedFeatures): Promise<void> {
  const hooksPath = resolve(projectRoot, 'src/hooks.ts')
  const hooksServerPath = resolve(projectRoot, 'src/hooks.server.ts')
  const generatedHooksPath = resolve(projectRoot, GENERATED_SVELTE_HOOKS_PATH)
  const generatedServerHooksPath = resolve(projectRoot, GENERATED_SVELTE_SERVER_HOOKS_PATH)
  const legacyHooksUserPath = resolve(projectRoot, 'src/hooks.user.ts')
  const legacyHooksServerUserPath = resolve(projectRoot, 'src/hooks.server.user.ts')
  const [hooksContents, hooksServerContents, legacyUserContents, legacyServerUserContents] = await Promise.all([
    readFileIfPresent(hooksPath),
    readFileIfPresent(hooksServerPath),
    readFileIfPresent(legacyHooksUserPath),
    readFileIfPresent(legacyHooksServerUserPath),
  ])

  if (legacyUserContents && (!hooksContents || isManagedPrepareArtifact(hooksContents))) {
    await writeFileIfChanged(hooksPath, legacyUserContents)
    await unlinkIfPresent(legacyHooksUserPath)
  } else if (legacyUserContents && hooksContents === legacyUserContents) {
    await unlinkIfPresent(legacyHooksUserPath)
  }

  if (legacyServerUserContents && (!hooksServerContents || isManagedPrepareArtifact(hooksServerContents))) {
    await writeFileIfChanged(hooksServerPath, legacyServerUserContents)
    await unlinkIfPresent(legacyHooksServerUserPath)
  } else if (legacyServerUserContents && hooksServerContents === legacyServerUserContents) {
    await unlinkIfPresent(legacyHooksServerUserPath)
  }

  const currentHooks = await readFileIfPresent(hooksPath)
  if (!currentHooks || isManagedPrepareArtifact(currentHooks) || isLegacySvelteTransportHook(currentHooks)) {
    await writeFileIfChanged(hooksPath, renderSvelteDefaultHooksModule())
  }

  const currentServerHooks = await readFileIfPresent(hooksServerPath)
  if (!currentServerHooks || isManagedPrepareArtifact(currentServerHooks) || isLegacySvelteServerHook(currentServerHooks)) {
    await writeFileIfChanged(hooksServerPath, renderSvelteDefaultServerHooksModule())
  }

  await writeFileIfChanged(generatedHooksPath, renderManagedSvelteHooksModule())
  await writeFileIfChanged(generatedServerHooksPath, renderManagedSvelteServerHooksModule(features))
  await ensureViteConfigWrapsSvelteKit(projectRoot)
}

async function removeLegacyManagedHoloHelper(path: string, managedContents: string): Promise<void> {
  const contents = await readFileIfPresent(path)
  const trimmedContents = contents?.trim()
  const trimmedManagedContents = managedContents.trim()
  const isLegacyManagedHelper = trimmedContents === [
    'import { createNextHoloHelpers } from \'@holo-js/adapter-next/runtime\'',
    '',
    'export const holo = createNextHoloHelpers()',
  ].join('\n') || trimmedContents === [
    'import { createSvelteKitHoloHelpers } from \'@holo-js/adapter-sveltekit\'',
    '',
    'export const holo = createSvelteKitHoloHelpers()',
  ].join('\n')

  if (trimmedContents === trimmedManagedContents || isLegacyManagedHelper) {
    await unlinkIfPresent(path)
  }
}

async function removeLegacyManagedRoute(
  path: string,
  markerGroups: readonly (readonly string[])[],
): Promise<void> {
  const contents = await readFileIfPresent(path)
  if (contents && markerGroups.some(markers => markers.every(marker => contents.includes(marker)))) {
    await unlinkIfPresent(path)
  }
}

async function directoryContainsText(path: string, pattern: string): Promise<boolean> {
  const entries = await readdir(path, { withFileTypes: true }).catch(() => [])
  for (const entry of entries) {
    const entryPath = resolve(path, entry.name)
    if (entry.isDirectory()) {
      if (await directoryContainsText(entryPath, pattern)) {
        return true
      }
      continue
    }

    if (!entry.isFile() || !/\.[cm]?[jt]s$/.test(entry.name)) {
      continue
    }

    const contents = await readFileIfPresent(entryPath)
    if (contents?.includes(pattern)) {
      return true
    }
  }

  return false
}

const realtimeDefinitionExtensions = new Set(['.ts', '.mts', '.cts', '.js', '.mjs', '.cjs'])

async function collectRealtimeDefinitionFiles(root: string): Promise<readonly string[]> {
  const entries = await readdir(root, { withFileTypes: true }).catch(() => [])
  const files = await Promise.all(entries.map(async (entry) => {
    const entryPath = resolve(root, entry.name)
    if (entry.isDirectory()) {
      return await collectRealtimeDefinitionFiles(entryPath)
    }

    return realtimeDefinitionExtensions.has(extname(entry.name)) ? [entryPath] : []
  }))

  return files.flat().sort((left, right) => left.localeCompare(right))
}

async function resolveNextRealtimeImportPaths(projectRoot: string): Promise<readonly string[]> {
  const generatedRoot = resolve(projectRoot, '.holo-js/generated/next')
  const files = await collectRealtimeDefinitionFiles(resolve(projectRoot, 'server/realtime'))
  const importPaths = files.map((filePath) => {
    const withoutExtension = filePath.slice(0, -extname(filePath).length)
    const importPath = relative(generatedRoot, withoutExtension).split(sep).join('/')
    return importPath.startsWith('.') ? importPath : `./${importPath}`
  })

  return importPaths
}

