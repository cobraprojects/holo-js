import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')

export async function generateCliWorkspaceCatalog(root = repoRoot) {
  const rootManifest = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'))
  const catalog = rootManifest.workspaces?.catalog

  if (!catalog || typeof catalog !== 'object' || Array.isArray(catalog)) {
    throw new Error('Root package.json is missing workspaces.catalog.')
  }

  const workspaceCatalogPath = join(root, 'packages/cli/src/generated/workspaceCatalog.ts')
  await mkdir(dirname(workspaceCatalogPath), { recursive: true })
  await writeFile(
    workspaceCatalogPath,
    [
      '// Generated by scripts/generate-cli-workspace-catalog.mjs. Do not edit by hand.',
      '',
      `export const WORKSPACE_CATALOG = Object.freeze(${JSON.stringify(catalog, null, 2)} as const)`,
      '',
    ].join('\n'),
    'utf8',
  )
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await generateCliWorkspaceCatalog()
}
